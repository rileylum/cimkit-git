"""cimkit-git install and uninstall: point git's hooks at cimkit-git hook, or stop. install.py is the old design's."""

import shlex
from pathlib import Path

from cimkit_git import git

HOOKS = ["pre-commit", "pre-push", "post-checkout", "post-merge", "post-rewrite", "post-stash"]

# The first git that reads hook.<name>.command and hook.<name>.event.
CONFIG_HOOKS = (2, 54)

MARKER = "# managed-by: cimkit-git"

# The line the pre-commit framework writes into every hook script it installs.
FRAMEWORK = "# File generated by pre-commit"
FRAMEWORK_CONFIG = ".pre-commit-config.yaml"

# Source must reach the object store byte for byte, or its recorded tree IDs stop matching.
NO_CONVERT = "**/*.aprx.src/** -text"


def install(root: Path, python: str) -> list[tuple[Path, str]]:
    """Register every hook. Returns each hook file install left alone because someone
    else wrote it, with the command that file must run to call cimkit-git."""
    config = git.version() >= CONFIG_HOOKS
    hooks = git.hooks_dir(root)
    ignore(root)
    left = []
    for event in HOOKS:
        # The absolute Python, because git's sh on Windows won't find Pro's conda env on PATH.
        # cimkit_git.cli, not cimkit_git: the package's __main__ is the old git cim command.
        command = f"{shlex.quote(python)} -m cimkit_git.cli hook {event}"
        # A friendly name equal to an event name is a fatal error in git.
        name, path = f"cimkit-git-{event}", hooks / event
        # Git runs a hooks-dir script beside a config hook, so whichever way install
        # registered a hook before a Git upgrade or downgrade must go, or it runs twice.
        if config:
            git.register_hook(root, name, event, command)
            if shim(path):
                path.unlink()
            continue
        git.unregister_hook(root, name)
        if ours(path):
            write_shim(path, command)
        else:
            left.append((path, f'{command} "$@"'))
    return left


def ignore(root: Path) -> None:
    """Add the ignore and attribute lines every repo needs, whoever runs its hooks."""
    add_lines(root / ".gitignore", ["*.aprx", "cimkit.local.toml"])
    add_lines(root / ".gitattributes", [NO_CONVERT])


def framework(root: Path) -> Path | None:
    """The first sign that the pre-commit framework runs this repo's hooks, or None.

    Git would run the framework's scripts beside install's hooks. The config file counts
    too: the hooks dir isn't committed, so a fresh clone has no scripts yet.
    """
    config = root / FRAMEWORK_CONFIG
    if config.is_file() and b"cimkit-git" in config.read_bytes():
        return config
    hooks = git.hooks_dir(root)
    return next((path for event in HOOKS if (path := hooks / event).is_file() and FRAMEWORK.encode() in path.read_bytes()), None)


def uninstall(root: Path) -> tuple[list[str], list[Path]]:
    """Remove every hook install registered, on any Git, so it also cleans up after an
    upgrade. Returns the config hook names and the shims it removed."""
    hooks = git.hooks_dir(root)
    names = [name for event in HOOKS if git.unregister_hook(root, name := f"cimkit-git-{event}")]
    shims = [path for event in HOOKS if shim(path := hooks / event)]
    for path in shims:
        path.unlink()
    return names, shims


def shim(path: Path) -> bool:
    """Whether path is a shim install wrote."""
    return path.is_file() and MARKER.encode() in path.read_bytes()


def ours(path: Path) -> bool:
    return not path.exists() or shim(path)


def add_lines(path: Path, lines: list[str]) -> None:
    """Append each line path lacks, so install can run again and a user's edits stay.

    Bytes, not text: text mode would rewrite every line ending on Windows.
    """
    data = path.read_bytes() if path.exists() else b""
    missing = [line for line in lines if line.encode() not in data.splitlines()]
    if missing:
        if data and not data.endswith(b"\n"):
            data += b"\n"
        path.write_bytes(data + "".join(line + "\n" for line in missing).encode())


def write_shim(path: Path, command: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    # LF only: git's sh on Windows reads a CR as part of the last argument.
    path.write_bytes(f'#!/bin/sh\n{MARKER}\nexec {command} "$@"\n'.encode())
    path.chmod(0o755)
